/* =====================================================================
   EcoҚуат — справочные данные
   Тарифы: ₸ за 1 кВт·ч с НДС, бытовые потребители, осень 2026.
   n1 / n2 — норма (граница 1-го и 2-го уровня) в кВт·ч НА 1 ЧЕЛОВЕКА в месяц.
   Лимит семьи = норма × число прописанных (так считают энергосбыты РК).
   status: ok — цена и границы с сайта энергосбыта / решения регулятора;
           part — цена 1-го уровня или все цены проверены, часть данных ориентир;
           approx — проверен только средний (2-й) уровень за август 2026,
                    остальные уровни рассчитаны по типовой пропорции (×0,77 / ×1,25).
   ===================================================================== */

const T_DEFAULT_NORM = { n1: 70, n2: 140, s1: 90, s2: 180 };   // схема как в Астане

function approxTiers(t2) {
  // В РК 3-й уровень почти везде = 2-й × 1,25; 1-й ≈ 2-й × 0,77
  return [round2(t2 * 0.77), t2, round2(t2 * 1.25)];
}
function round2(x) { return Math.round(x * 100) / 100; }

